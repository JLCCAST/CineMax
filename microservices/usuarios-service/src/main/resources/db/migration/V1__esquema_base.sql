-- Esquema base de usuarios_db (PostgreSQL).
--
-- Reproduce el esquema que existía antes de Flyway: las tablas del init-script
-- (role, permission, role_permission, document_type) más user_account, que la
-- creaba Hibernate con ddl-auto=update. Por eso user_account usa una columna
-- IDENTITY y conserva los nombres de restricción que generó Hibernate (uk..., fk...).
--
-- No edites este archivo: un cambio de esquema va en una migración nueva (V3, V4...).

CREATE TABLE role (
    id_role   SERIAL PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE permission (
    id_permission   SERIAL PRIMARY KEY,
    permission_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE role_permission (
    id_role       INTEGER NOT NULL REFERENCES role (id_role) ON DELETE CASCADE,
    id_permission INTEGER NOT NULL REFERENCES permission (id_permission) ON DELETE CASCADE,
    PRIMARY KEY (id_role, id_permission)
);

CREATE TABLE document_type (
    id_doc_type SERIAL PRIMARY KEY,
    doc_name    VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE user_account (
    id_user               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    datebirth             DATE,
    document_number       VARCHAR(20)  NOT NULL,
    email                 VARCHAR(150) NOT NULL,
    first_name            VARCHAR(100) NOT NULL,
    id_venue              INTEGER,
    image_url             VARCHAR(255),
    last_name             VARCHAR(100) NOT NULL,
    password              VARCHAR(255) NOT NULL,
    phone                 VARCHAR(20),
    reset_password_token  VARCHAR(255),
    status                VARCHAR(20)  NOT NULL,
    token_expiration_date TIMESTAMP(6),
    id_doc_type           INTEGER      NOT NULL,
    id_role               INTEGER      NOT NULL,
    CONSTRAINT user_account_pkey PRIMARY KEY (id_user),
    CONSTRAINT ukhl02wv5hym99ys465woijmfib UNIQUE (email),
    CONSTRAINT fkgkw7ma4q3ir0loj4p2h7srfep FOREIGN KEY (id_role) REFERENCES role (id_role),
    CONSTRAINT fkie540ovn8u3f7kib1qute7c16 FOREIGN KEY (id_doc_type) REFERENCES document_type (id_doc_type)
);
