-- Esquema base de sales_db (PostgreSQL).
--
-- Reproduce el esquema que existía antes de Flyway: las tablas del init-script
-- (transaction_status, sale_transaction, sale_ticket_detail, sale_snack_detail)
-- más lo que agregaba Hibernate con ddl-auto=update: las tablas promotion_type y
-- promotion, y la columna sale_transaction.id_promotion. Lo que creó Hibernate
-- usa columnas IDENTITY y conserva los nombres de restricción que generó (uk..., fk...).
--
-- No edites este archivo: un cambio de esquema va en una migración nueva (V3, V4...).

CREATE TABLE transaction_status (
    id_transaction_status SERIAL PRIMARY KEY,
    name_status           VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE promotion_type (
    id_promotion_type   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name_promotion_type VARCHAR(50) NOT NULL,
    CONSTRAINT promotion_type_pkey PRIMARY KEY (id_promotion_type),
    CONSTRAINT uk1fy27uegalvs5j7wwnrt3sk3j UNIQUE (name_promotion_type)
);

CREATE TABLE promotion (
    id_promotion            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    created_at              TIMESTAMP(6),
    day_of_week             VARCHAR(20),
    discount_fixed_amount   NUMERIC(10,2),
    discount_percentage     NUMERIC(5,2),
    end_date                DATE         NOT NULL,
    exclude_premiere_movies BOOLEAN,
    image_url_promotion     VARCHAR(250),
    max_discount_amount     NUMERIC(10,2),
    minimum_purchase_amount NUMERIC(10,2),
    minimum_ticket_quantity INTEGER,
    name_promotion          VARCHAR(100) NOT NULL,
    promotion_code          VARCHAR(30),
    start_date              DATE         NOT NULL,
    status                  VARCHAR(20),
    updated_at              TIMESTAMP(6),
    id_promotion_type       INTEGER      NOT NULL,
    CONSTRAINT promotion_pkey PRIMARY KEY (id_promotion),
    CONSTRAINT uko72hlunsj1rlisekchpp6e9v UNIQUE (promotion_code),
    CONSTRAINT promotion_discount_fixed_amount_check CHECK (discount_fixed_amount >= 0),
    CONSTRAINT promotion_discount_percentage_check CHECK (discount_percentage >= 0),
    CONSTRAINT fkarxqye4ia1v5uypipr0m54h83 FOREIGN KEY (id_promotion_type)
        REFERENCES promotion_type (id_promotion_type)
);

CREATE TABLE sale_transaction (
    id_transaction        SERIAL PRIMARY KEY,
    id_user               INTEGER       NOT NULL,
    id_transaction_status INTEGER       NOT NULL,
    subtotal              NUMERIC(10,2) NOT NULL,
    discount_amount       NUMERIC(10,2) NOT NULL DEFAULT 0,
    total_amount          NUMERIC(10,2) NOT NULL,
    payment_method        VARCHAR(50),
    created_at            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_date          TIMESTAMP,
    qr_code_data          VARCHAR(250),
    id_promotion          INTEGER,
    CONSTRAINT fk_sale_transaction_status FOREIGN KEY (id_transaction_status)
        REFERENCES transaction_status (id_transaction_status),
    CONSTRAINT fkhlavcm8ut32h7w5q1hxp0mn3e FOREIGN KEY (id_promotion)
        REFERENCES promotion (id_promotion)
);

CREATE TABLE sale_ticket_detail (
    id_ticket      SERIAL PRIMARY KEY,
    id_transaction INTEGER       NOT NULL,
    id_showtime    VARCHAR(24)   NOT NULL,
    id_seat        INTEGER       NOT NULL,
    ticket_price   NUMERIC(10,2) NOT NULL,
    is_used        BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_ticket_transaction FOREIGN KEY (id_transaction)
        REFERENCES sale_transaction (id_transaction),
    -- Impide vender dos veces la misma butaca en la misma función.
    CONSTRAINT uq_ticket_seat_showtime UNIQUE (id_showtime, id_seat)
);

CREATE TABLE sale_snack_detail (
    id_detail      SERIAL PRIMARY KEY,
    id_transaction INTEGER       NOT NULL,
    id_snack       INTEGER       NOT NULL,
    quantity       INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price     NUMERIC(10,2) NOT NULL,
    is_delivered   BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_snack_detail_transaction FOREIGN KEY (id_transaction)
        REFERENCES sale_transaction (id_transaction)
);
